def test_nin_mixed_int_float_list_uses_numeric_cast(pgvector_index) -> None:
    clause, params, next_idx = pgvector_index._translate_comparison_filter(
        ComparisonFilter(type="nin", key="year", value=[2023.5, 1]), param_idx=1
    )

    assert clause == f"({_expr('year')})::numeric NOT IN ($1, $2)"
    assert params == [2023.5, 1]
