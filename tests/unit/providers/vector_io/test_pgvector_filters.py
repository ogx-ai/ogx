def test_in_filter_respects_param_idx(pgvector_index) -> None:
    clause, _, next_idx = pgvector_index._translate_comparison_filter(
        ComparisonFilter(type="in", key="year", value=[2023, 2024]), param_idx=2
    )

    assert clause == f"({_expr('year')})::numeric IN ($2, $3)"
    assert next_idx == 4


def test_in_rejects_non_list_value(pgvector_index) -> None:
    with pytest.raises(ValueError, match="'in' filter requires a list value"):
        pgvector_index._translate_comparison_filter(
            ComparisonFilter(type="in", key="published", value=True), param_idx=1
        )


def test_nin_rejects_non_list_value(pgvector_index) -> None:
    with pytest.raises(ValueError, match="'nin' filter requires a list value"):
        pgvector_index._translate_comparison_filter(
            ComparisonFilter(type="nin", key="published", value=True), param_idx=1
        )


def test_in_cast_consistent_with_scalar_bool_comparison(pgvector_index) -> None:
    scalar_clause, _, _ = pgvector_index._translate_comparison_filter(
        ComparisonFilter(type="eq", key="published", value=True), param_idx=1
    )
    list_clause, _, _ = pgvector_index._translate_comparison_filter(
        ComparisonFilter(type="in", key="published", value=[True]), param_idx=1
    )

    assert scalar_clause == f"({_expr('published')})::boolean = $1"
    assert list_clause.startswith(f"({_expr('published')})::boolean IN ")


def test_compound_and_threads_params_for_in_filters(pgvector_index) -> None:
    clause, params, next_idx = pgvector_index._translate_compound_filter(
        CompoundFilter(
            type="and",
            filters=[
                ComparisonFilter(type="in", key="published", value=[True]),
                ComparisonFilter(type="nin", key="topic", value=["ai"]),
            ],
        ),
        param_idx=1,
    )

    assert clause == f"(({_expr('published')})::boolean IN ($1)) AND ({_expr('topic')} NOT IN ($2))"
    assert params == [True, "ai"]
    assert next_idx == 3


def test_unknown_comparison_operator_rejected(pgvector_index) -> None:
    unsupported = ComparisonFilter.model_construct(type="between", key="year", value=[2023])

    with pytest.raises(ValueError, match="Unknown comparison operator"):
        pgvector_index._translate_comparison_filter(unsupported, param_idx=1)
